//! Runs a compiled program in the current process: the same Cranelift code generation as the
//! object writer (`codegen::generate`), into a `cranelift-jit` module instead.
//!
//! `compile_and_load(source, options)` lowers and compiles the source and returns a [`Game`]: typed
//! access to the exported functions (`ts_<prefix>init`, `ts_<prefix>__uiSignatures`, ...) and the
//! component class table (`classes()`, the run-time form of the generated bindings' `classes()`).
//!
//! Imports are resolved by name: `platypus_ts_rt`'s `symbols()` (the runtime, generated by its build
//! script), every namespace whose manifest was read (`platypus_api::symbol`, registered by
//! `Namespace::to_json`), and the tables in [`JitOptions::symbols`] (the host adds `platypus_ts_ui`'s).
//! A missing symbol is an error naming it, before any code runs.
//!
//! A game's memory is never freed (code of an old game may still be referenced by rooted
//! closures, timers or the GC's tables when a hot reload swaps it for a new one).

use crate::classmeta::{ClassMeta, class_meta};
use crate::{codegen, ir, sroa};
use cranelift_jit::{JITBuilder, JITModule};
use cranelift_module::default_libcall_names;
use std::collections::HashMap;

/// What to compile and how.
#[derive(Default)]
pub struct JitOptions<'a> {
    /// Cranelift `opt_level`; empty means `speed`.
    pub opt: &'a str,
    /// Exported functions are `ts_<prefix><name>`.
    pub prefix: &'a str,
    /// First object header number; programs sharing a process need ranges 1000 apart.
    pub struct_base: u32,
    /// The engine API manifests (JSON) the source may call.
    pub manifests: &'a [String],
    /// More symbols (name, address) imports may name.
    pub symbols: Vec<(&'static str, usize)>,
    /// A debug build: a check before every statement that calls the debugger's hook
    /// (`crate::debug`) while a breakpoint, pause or step is set. Slower; for debugging only.
    pub debug: bool,
}

/// A compiled and loaded program.
pub struct Game {
    // Never dropped: see the module docs.
    _module: std::mem::ManuallyDrop<JitModule>,
    /// Every function's address by symbol: exported `ts_<prefix>..` and local ones.
    funcs: HashMap<String, usize>,
    /// Machine-code ranges `(start, end, line)` by address, ascending: `line` is a line of the
    /// bundled source (debug info, see `docs/research/platypus-ts-debug-info.md`).
    line_table: Vec<(usize, usize, u32)>,
    meta: Vec<ClassMeta>,
    prefix: String,
    /// Wall-clock time of lowering and of code generation plus linking.
    pub lower_time: std::time::Duration,
    pub codegen_time: std::time::Duration,
}

/// `JITModule` holds raw pointers, so it is not `Send`; it is built on a worker thread (lowering
/// needs a big stack) and then used by one thread only.
#[allow(dead_code)]
struct JitModule(JITModule);
// SAFETY: the module's memory is plain code and data; nothing in it is tied to the thread.
unsafe impl Send for JitModule {}

// The libcalls Cranelift may emit (`default_libcall_names`) when the CPU lacks an instruction.
extern "C" fn j_floor(x: f64) -> f64 {
    x.floor()
}
extern "C" fn j_floorf(x: f32) -> f32 {
    x.floor()
}
extern "C" fn j_ceil(x: f64) -> f64 {
    x.ceil()
}
extern "C" fn j_ceilf(x: f32) -> f32 {
    x.ceil()
}
extern "C" fn j_trunc(x: f64) -> f64 {
    x.trunc()
}
extern "C" fn j_truncf(x: f32) -> f32 {
    x.trunc()
}
extern "C" fn j_nearest(x: f64) -> f64 {
    x.round_ties_even()
}
extern "C" fn j_nearestf(x: f32) -> f32 {
    x.round_ties_even()
}
extern "C" fn j_fma(a: f64, b: f64, c: f64) -> f64 {
    a.mul_add(b, c)
}
extern "C" fn j_fmaf(a: f32, b: f32, c: f32) -> f32 {
    a.mul_add(b, c)
}
unsafe extern "C" fn j_memcpy(d: *mut u8, s: *const u8, n: usize) -> *mut u8 {
    unsafe { std::ptr::copy_nonoverlapping(s, d, n) };
    d
}
unsafe extern "C" fn j_memmove(d: *mut u8, s: *const u8, n: usize) -> *mut u8 {
    unsafe { std::ptr::copy(s, d, n) };
    d
}
unsafe extern "C" fn j_memset(d: *mut u8, c: i32, n: usize) -> *mut u8 {
    unsafe { std::ptr::write_bytes(d, c as u8, n) };
    d
}
unsafe extern "C" fn j_memcmp(a: *const u8, b: *const u8, n: usize) -> i32 {
    let (a, b) = unsafe {
        (
            std::slice::from_raw_parts(a, n),
            std::slice::from_raw_parts(b, n),
        )
    };
    match a.cmp(b) {
        std::cmp::Ordering::Less => -1,
        std::cmp::Ordering::Equal => 0,
        std::cmp::Ordering::Greater => 1,
    }
}

fn libcalls() -> Vec<(&'static str, usize)> {
    vec![
        ("floor", j_floor as *const () as usize),
        ("floorf", j_floorf as *const () as usize),
        ("ceil", j_ceil as *const () as usize),
        ("ceilf", j_ceilf as *const () as usize),
        ("trunc", j_trunc as *const () as usize),
        ("truncf", j_truncf as *const () as usize),
        ("nearbyint", j_nearest as *const () as usize),
        ("nearbyintf", j_nearestf as *const () as usize),
        ("fma", j_fma as *const () as usize),
        ("fmaf", j_fmaf as *const () as usize),
        ("memcpy", j_memcpy as *const () as usize),
        ("memmove", j_memmove as *const () as usize),
        ("memset", j_memset as *const () as usize),
        ("memcmp", j_memcmp as *const () as usize),
    ]
}

/// What a debugger needs to read a value of this type.
fn show_ty(
    t: &ir::Ty,
    tags: &std::sync::Arc<Vec<String>>,
    structs: &std::sync::Arc<crate::debug::Structs>,
) -> crate::debug::ShowTy {
    use crate::debug::ShowTy;
    match t {
        ir::Ty::Num => ShowTy::Num,
        ir::Ty::Bool => ShowTy::Bool,
        ir::Ty::Lit => ShowTy::Lit(tags.clone()),
        ir::Ty::Str => ShowTy::Str,
        ir::Ty::Obj(id) => ShowTy::Obj(structs.clone(), *id),
        ir::Ty::Arr(inner) => ShowTy::Arr(Box::new(show_ty(inner, tags, structs))),
        ir::Ty::Cell(inner) => ShowTy::Cell(Box::new(show_ty(inner, tags, structs))),
        ir::Ty::Nullable(inner) => ShowTy::Nullable(Box::new(show_ty(inner, tags, structs))),
        other => ShowTy::Other(format!("{other}")),
    }
}

/// The named locals of every function of the module, and the struct table they refer to.
fn describe_functions(m: &ir::Module) -> Vec<crate::debug::FuncDebug> {
    let tags = std::sync::Arc::new(m.tags.clone());
    let structs = std::sync::Arc::new(crate::debug::Structs::default());
    let infos = m
        .structs
        .iter()
        .map(|st| crate::debug::StructInfo {
            name: st.name.clone(),
            fields: st
                .fields
                .iter()
                .enumerate()
                .map(|(i, f)| {
                    (
                        f.name.clone(),
                        ir::field_offset(i) as usize,
                        show_ty(&f.ty, &tags, &structs),
                    )
                })
                .collect(),
        })
        .collect();
    let _ = structs.0.set(infos);
    m.funcs
        .iter()
        .enumerate()
        .map(|(i, f)| crate::debug::FuncDebug {
            name: f.name.clone(),
            locals: m
                .local_names
                .get(&i)
                .into_iter()
                .flatten()
                .filter(|(v, _)| (*v as usize) < f.locals.len())
                .map(|(v, name)| {
                    (
                        *v as usize,
                        name.clone(),
                        show_ty(&f.locals[*v as usize], &tags, &structs),
                    )
                })
                .collect(),
        })
        .collect()
}

/// The imports of a module that no table can resolve (so the error comes before any code runs).
fn missing_symbols(m: &ir::Module, known: &HashMap<&str, usize>) -> Vec<String> {
    let mut out: Vec<String> = m
        .externs
        .iter()
        .map(|d| d.symbol.clone())
        .filter(|s| !known.contains_key(s.as_str()) && platypus_api::symbol(s).is_none())
        .collect();
    out.sort();
    out.dedup();
    out
}

/// Lowers `src` (on a thread with a big stack) and compiles it into this process.
pub fn compile_and_load(src: &str, options: &JitOptions) -> Result<Game, String> {
    let opt = if options.opt.is_empty() {
        "speed"
    } else {
        options.opt
    };
    let t0 = std::time::Instant::now();
    let (module, lower_time) = std::thread::scope(|s| {
        std::thread::Builder::new()
            .stack_size(64 << 20)
            .spawn_scoped(s, || -> Result<(ir::Module, _), String> {
                let mut m = crate::lower::lower_source_with(src, options.manifests)?;
                m.prefix = options.prefix.to_string();
                m.struct_base = options.struct_base;
                if options.debug {
                    m.debug_armed = crate::debug::armed_addr();
                }
                let mut lap = crate::timing::Lap::start();
                sroa::run(&mut m);
                if options.debug {
                    m.debug_base = crate::debug::next_base(m.funcs.len());
                }
                lap.mark("IR passes (sroa)");
                Ok((m, t0.elapsed()))
            })
            .map_err(|e| e.to_string())?
            .join()
            .map_err(|_| "compiler panicked".to_string())?
    })?;

    let t1 = std::time::Instant::now();
    let mut lap = crate::timing::Lap::start();
    let mut known: HashMap<&'static str, usize> = HashMap::new();
    known.extend(libcalls());
    known.extend(platypus_ts_rt::symbols());
    known.extend(options.symbols.iter().copied());
    if options.debug {
        known.insert("ts_dbg_line", crate::debug::hook_addr());
        known.insert("ts_dbg_throw", crate::debug::throw_hook_addr());
    }
    let missing = missing_symbols(&module, &known);
    if !missing.is_empty() {
        return Err(format!(
            "the program calls engine functions the host does not provide: {}",
            missing.join(", ")
        ));
    }
    let isa = codegen::host_isa(opt, true)?;
    let mut builder = JITBuilder::with_isa(isa, default_libcall_names());
    let table: HashMap<String, usize> =
        known.into_iter().map(|(k, v)| (k.to_string(), v)).collect();
    builder.symbol_lookup_fn(Box::new(move |name| {
        table
            .get(name)
            .copied()
            .or_else(|| platypus_api::symbol(name))
            .map(|a| a as *const u8)
    }));
    let mut jit = JITModule::new(builder);
    lap.mark("JIT set-up (symbols, ISA)");
    // Code generation recurses over expressions as lowering does (a big JSX tree nests calls a few
    // hundred deep): it gets a big stack too, not the host's main thread.
    let symbols = std::thread::scope(|s| {
        std::thread::Builder::new()
            .stack_size(64 << 20)
            .spawn_scoped(s, || codegen::generate(&mut jit, &module, true))
            .map_err(|e| e.to_string())?
            .join()
            .map_err(|_| "code generation panicked".to_string())?
    })?;
    lap.mark("Cranelift code generation");
    jit.finalize_definitions().map_err(|e| e.to_string())?;
    let mut line_table: Vec<(usize, usize, u32)> = Vec::new();
    let mut funcs: HashMap<String, usize> = HashMap::new();
    let mut func_addrs: Vec<usize> = Vec::new();
    #[cfg(windows)]
    let mut unwind: Vec<crate::unwind::FnUnwind> = Vec::new();
    for (((name, id), lines), info) in symbols
        .names
        .into_iter()
        .zip(symbols.lines)
        .zip(symbols.unwind)
    {
        let base = jit.get_finalized_function(id) as usize;
        #[cfg(windows)]
        if let Some((size, info)) = info {
            unwind.push(crate::unwind::FnUnwind {
                start: base,
                size,
                info,
            });
        }
        #[cfg(not(windows))]
        let _ = info;
        line_table.extend(
            lines
                .into_iter()
                .map(|(a, b, line)| (base + a as usize, base + b as usize, line)),
        );
        func_addrs.push(base);
        funcs.insert(name, base);
    }
    line_table.sort_unstable_by_key(|(a, _, _)| *a);
    if options.debug {
        crate::debug::register(module.debug_base, describe_functions(&module));
        let names: Vec<(usize, String)> = module
            .funcs
            .iter()
            .zip(&func_addrs)
            .map(|(f, a)| (*a, f.name.clone()))
            .collect();
        crate::debug::set_code(line_table.clone(), names);
    }
    // So the system can walk a stack through compiled frames (a crash report's call stack).
    #[cfg(windows)]
    crate::unwind::register(unwind)?;
    lap.mark("JIT linking and finalising");
    Ok(Game {
        _module: std::mem::ManuallyDrop::new(JitModule(jit)),
        funcs,
        line_table,
        meta: class_meta(&module),
        prefix: options.prefix.to_string(),
        lower_time,
        codegen_time: t1.elapsed(),
    })
}

impl Game {
    /// The address of the exported function `ts_<prefix><name>`, given `name`.
    pub fn function(&self, name: &str) -> Option<usize> {
        self.funcs
            .get(&format!("ts_{}{name}", self.prefix))
            .copied()
    }

    /// The names of the exported functions (without `ts_<prefix>`).
    pub fn function_names(&self) -> Vec<String> {
        let head = format!("ts_{}", self.prefix);
        let mut v: Vec<String> = self
            .funcs
            .keys()
            .filter_map(|k| k.strip_prefix(&head).map(str::to_string))
            .collect();
        v.sort();
        v
    }

    /// Every compiled function, exported and local, as (symbol, address): what a crash report
    /// needs to name the function a fault is in (`platypus_app/src/crash.rs`).
    pub fn code_symbols(&self) -> Vec<(String, usize)> {
        self.funcs.iter().map(|(n, a)| (n.clone(), *a)).collect()
    }

    /// The source line ranges of the compiled code, `(start, end, line)` by address: what a crash
    /// report maps a fault address to a line of the bundled source with.
    pub fn line_table(&self) -> &[(usize, usize, u32)] {
        &self.line_table
    }

    /// Runs the top-level code (module variables, `register(..)`, mounting). Call it once, on the
    /// thread that will run the game.
    pub fn init(&self) -> Result<(), String> {
        let a = self.function("init").ok_or("the program has no init")?;
        // A new run of the top level starts with no registrations and no pending modules.
        platypus_ts_rt::startup_reset();
        // SAFETY: `init` takes nothing and returns nothing.
        unsafe { std::mem::transmute::<usize, unsafe extern "C" fn()>(a)() };
        Ok(())
    }

    /// The registered component classes as data.
    pub fn class_meta(&self) -> &[ClassMeta] {
        &self.meta
    }

    /// The class table for `platypus_ts_rt::NativeHost`: the run-time form of the bindings' `classes()`.
    /// The strings and tables are leaked (a few hundred bytes per class per load).
    pub fn classes(&self) -> Result<Vec<platypus_ts_rt::NativeClass>, String> {
        type Create = unsafe extern "C" fn(f64, u64) -> *mut u8;
        type Hook = unsafe extern "C" fn(*mut u8, f64);
        type Contact = unsafe extern "C" fn(*mut u8, u64, u64);
        let addr = |sym: &str| {
            self.funcs
                .get(sym)
                .copied()
                .ok_or_else(|| format!("missing symbol {sym}"))
        };
        let mut out = Vec::new();
        for c in &self.meta {
            let mut hooks: [Option<Hook>; 9] = [None; 9];
            for (i, h) in c.hooks.iter().enumerate() {
                if let Some(h) = h {
                    // SAFETY: the compiled hook takes (this, dt).
                    hooks[i] = Some(unsafe { std::mem::transmute::<usize, Hook>(addr(h)?) });
                }
            }
            let mut contact_hooks: [Option<Contact>; 6] = [None; 6];
            for (i, h) in c.contact_hooks.iter().enumerate() {
                if let Some(h) = h {
                    // SAFETY: the compiled hook takes (this, collision, collider).
                    contact_hooks[i] =
                        Some(unsafe { std::mem::transmute::<usize, Contact>(addr(h)?) });
                }
            }
            let props: Vec<(&'static str, usize, &'static str)> = c
                .props
                .iter()
                .map(|(n, o, t)| {
                    (
                        &*Box::leak(n.clone().into_boxed_str()),
                        *o,
                        &*Box::leak(t.clone().into_boxed_str()),
                    )
                })
                .collect();
            out.push(platypus_ts_rt::NativeClass {
                name: Box::leak(c.name.clone().into_boxed_str()),
                sid: c.sid,
                bases: Box::leak(c.bases.clone().into_boxed_slice()),
                // SAFETY: the constructor takes (id, object) and ignores the object when the class
                // does not use one (the extra register argument is harmless in the C ABI).
                create: unsafe { std::mem::transmute::<usize, Create>(addr(&c.create)?) },
                hooks,
                contact_hooks,
                props: Box::leak(props.into_boxed_slice()),
            });
        }
        Ok(out)
    }
}
